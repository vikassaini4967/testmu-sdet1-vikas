import type { TestInfo } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import { explainFailure, type LiveTools } from './failure-explainer.js';
import { appendFailure, testIdOf } from './history-store.js';
import { aiConfig, disabledReason } from './config.js';
import { VERDICT_LABEL, type Explanation, type FailureContext } from './types.js';

/** Set by the reporter in onBegin, inherited by workers. */
export const RUN_ID = process.env.AI_RUN_ID ?? `local-${Date.now()}`;

function writeExplanationFile(ctx: FailureContext, markdown: string): void {
  try {
    const dir = path.join(aiConfig.paths.reportDir, 'explanations');
    fs.mkdirSync(dir, { recursive: true });
    const slug = `${ctx.project}-${ctx.testTitle}`.toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 90);
    fs.writeFileSync(path.join(dir, `${slug}.md`), markdown, 'utf8');
  } catch {
    // Report attachment already holds it; the file is a convenience.
  }
}

function render(ctx: FailureContext, e: Explanation): string {
  const healed = e.healedLocator
    ? `\n## 🩹 Proposed locator\n\`${e.healedLocator.expression}\` — ${
        e.healedLocator.verified
          ? '**verified**: matched exactly 1 visible element on the live page at failure time.'
          : `**not verified** (probe matched ${e.healedLocator.matches < 0 ? 'nothing / was never run' : e.healedLocator.matches}). Treat as a hint only.`
      }\n`
    : '';

  const probes = e.probes.length
    ? `\n<details><summary>Locator probes run by the agent (${e.probes.length})</summary>\n\n${e.probes
        .map((p) => `- \`${p.expression}\` → ${p.error ? `error: ${p.error}` : `${p.count} match(es), visible: ${p.visible}`}`)
        .join('\n')}\n</details>\n`
    : '';

  return `# AI failure triage

**${e.summary}**

| | |
|---|---|
| Verdict | ${VERDICT_LABEL[e.verdict]} |
| Confidence | ${e.confidence} |
| Agent steps | ${e.steps} |
| Evidence pulled | ${e.toolsUsed.length ? e.toolsUsed.join(' → ') : 'none (concluded from the error and source alone)'} |
| Model | \`${e.provider}/${e.model}\` · ${e.usage.calls} call(s) · ${e.usage.inputTokens.toLocaleString()} in / ${e.usage.outputTokens.toLocaleString()} out tokens |

## What broke
${e.rootCause}

## Suggested fix
${e.suggestedFix}
${healed}${probes}
---
<sub>Generated by \`src/ai/failure-explainer.ts\` — live LLM call, agentic tool-use loop. Test: \`${ctx.testTitle}\`. \`ai-failure-context.json\` shows exactly what the model was given.</sub>
`;
}

/**
 * Runs triage for a failed test and attaches the result to the Playwright
 * report, so the explanation sits inside the normal test output rather than
 * in a side channel someone has to remember to open.
 *
 * Every failed attempt goes into the cross-run history (that is what the
 * classifier learns from), but only the FINAL attempt is sent to the LLM — a
 * failure that passes on retry needs a flakiness label, not a diagnosis, and
 * explaining each retry would triple the cost of a broken build.
 */
export async function triageAndAttach(testInfo: TestInfo, ctx: FailureContext, live: LiveTools = {}): Promise<void> {
  const testId = testIdOf(ctx.testFile, ctx.testTitle, ctx.project);
  const isFinalAttempt = testInfo.retry >= testInfo.project.retries;
  const skipReason = disabledReason();

  let explanation: Explanation | null = null;

  if (skipReason) {
    await testInfo.attach('ai-triage-skipped.txt', {
      body: `AI triage did not run.\nReason: ${skipReason}`,
      contentType: 'text/plain',
    });
  } else if (!isFinalAttempt) {
    await testInfo.attach('ai-triage-deferred.txt', {
      body: `Attempt ${testInfo.retry + 1} of ${testInfo.project.retries + 1} failed. Triage runs on the final attempt only; if a retry passes, the run-level classifier records this test as flaky.`,
      contentType: 'text/plain',
    });
  } else {
    explanation = await explainFailure(ctx, live, RUN_ID);
    if (explanation) {
      const markdown = render(ctx, explanation);
      await testInfo.attach('ai-failure-explanation.md', { body: markdown, contentType: 'text/markdown' });
      // Also as a plain file, so CI can upload explanations without the HTML report.
      writeExplanationFile(ctx, markdown);
      await testInfo.attach('ai-failure-context.json', {
        body: JSON.stringify(ctx, null, 2),
        contentType: 'application/json',
      });
      if (explanation.healedLocator?.verified) {
        testInfo.annotations.push({ type: 'ai-heal', description: explanation.healedLocator.expression });
      }
    }
  }

  appendFailure({
    ts: Date.now(),
    runId: RUN_ID,
    testId,
    testTitle: ctx.testTitle,
    testFile: ctx.testFile,
    project: ctx.project,
    retry: ctx.retry,
    errorMessage: ctx.errorMessage,
    explanation,
  });
}
